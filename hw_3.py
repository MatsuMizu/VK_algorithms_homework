# 1. Найти корень числа (округление вниз)
def my_sqrt(n):
    # Ищем целое x такое, что x*x <= n, но (x+1)*(x+1) > n
    # Корень числа n всегда находится в диапазоне [0, n]:
    #   - для n=0 корень 0, для n=1 корень 1
    #   - для n>=1 корень <= n (так как sqrt(n) <= n)
    # Это определяет границы поиска.
    left, right = 0, n
    ans = 0
    while left <= right:
        mid = (left + right) // 2
        if mid * mid <= n:
            # mid - допустимый кандидат (квадрат не превышает n),
            # запоминаем его и пробуем найти больший
            ans = mid
            left = mid + 1
        else:
            # mid слишком большой, ищем в левой половине
            right = mid - 1
    return ans

# Почему O(log n): на каждом итерации диапазон [left, right]
# сужается вдвое. Диапазон изначально равен n, поэтому
# максимум итераций ~ log2(n).


# 2. Два ксерокса
def min_time_to_copy(n, x, y):
    # За время t минут:
    #   первая машина успевает сделать floor(t / x) копий
    #   вторая машина успевает сделать floor(t / y) копий
    # Всего: floor(t/x) + floor(t/y) копий.
    # Условие достаточности: floor(t/x) + floor(t/y) >= n.
    #
    # Если за время t копий достаточно,
    # то за любое t' > t копий тоже достаточно.
    # Поэтому можем бинарным поиском найти минимальное t.
    #
    # Нижняя граница: 0 минут
    # Верхняя граница: n * min(x, y) - самая быстрая машина
    #   делает все n копий сама (это точно хватит).
    left, right = 0, n * min(x, y)
    while left < right:
        mid = (left + right) // 2
        if mid // x + mid // y >= n:
            right = mid
        else:
            left = mid + 1
    return left

# Сложность: O(log(n * min(x,y))), каждая проверка O(1).


# 3. Накормить животных
def max_animals_fed(animals, portions):
    # Жадный алгоритм: сначала кормим тех, кому нужно меньше еды.
    #
    # Если мы имеем порцию, которая может накормить животное A
    # (ему нужно a), и она тоже может накормить животное B
    # (ему нужно b > a), то выгоднее дать ее A. Почему: B и так
    # сможет поедать только большие порции, а A - любые.
    # То есть "маленькая" порция "расходуется" на "маленькое"
    # животное, оставляя большие порции для больших животных.
    #
    # Алгоритм:
    # 1) Сортируем животных по возрастанию (меньшие потребности - первыми)
    # 2) Сортируем порции по возрастанию
    # 3) Идем по животным, для каждого берем наименьшую
    #    оставшуюся порцию, которая ему подходит.
    animals.sort()
    portions.sort()
    fed = 0
    p = 0  # индекс текущей порции
    for a in animals:
        # Пропускаем порции, которые слишком малы для текущего животного
        while p < len(portions) and portions[p] < a:
            p += 1
        if p == len(portions):
            # Порций больше нет - остального не накормить
            break
        # Даем текущую порцию животному
        p += 1
        fed += 1
    return fed

# Сложность: O(n log n + m log m) на сортировку + O(n + m) на проход.


# 4. Лишняя буква
def find_extra_char(a, b):
    # b = перестановка a + одна дополнительная буква.
    #
    # XOR: x ^ x = 0,  x ^ 0 = x
    # Если взять XOR от всех символов из a и b,
    # то все пары одинаковых символов дадут 0,
    # а останется только та буква, которая есть в b, но не в a.
    result = 0
    for ch in a:
        result ^= ord(ch)
    for ch in b:
        result ^= ord(ch)
    return chr(result)
# Сложность O(n).


# 5. Сумма двух элементов
def two_sum(nums, target):
    # Идем по массиву один раз и храним уже
    # просмотренные числа в словаре {значение: индекс}.
    # Для текущего nums[i] ищем в словаре
    # число target - nums[i]. Если нашли, значит пара готова:
    #   nums[seen[complement]] + nums[i] == target
    # Если не нашли, кладем текущий элемент в словарь.
    #
    # Каждый элемент используется ровно один раз.
    # Проверка "было ли такое число раньше" через `in seen` за O(1),
    # вместо перебора всех предыдущих элементов во внутреннем цикле.
    # Итого один проход: O(n) вместо O(n^2).
    seen = {}  # значение -> индекс в массиве
    for i, num in enumerate(nums):
        complement = target - num
        if complement in seen:
            return [seen[complement], i]
        seen[num] = i
    return []  # подходящая пара не найдена

# Сложность: O(n) по времени (один проход + O(1) на поиск в dict)

# 6. Массив анаграмм
def group_anagrams(strs):
    # Отсортированная строка - это "ключ" группы анаграмм.
    #
    # Алгоритм:
    # 1) Берем строку, сортируем ее символы -> ключ
    # 2) Ключи с одинаковым значением кладем в одну группу
    # 3) Возвращаем список всех групп
    groups = {}  # key: сортированная строка -> [исходные строки]
    for s in strs:
        key = tuple(sorted(s))
        if key not in groups:
            groups[key] = []
        groups[key].append(s)
    return list(groups.values())

# Сложность: O(n * k * log k), где n - кол-во строк,
# k - максимальная длина строки.

# 6. Массив анаграмм: если алфавит известен
def group_anagrams_opt(strs):
    # Если известен алфавит (например, латиница с 26 символами),
    # то можно за O(n * k), где k - максимальная длина строки.
    # Ключ группы = счетчики символов.
    # Проходим по строке и для каждого
    # символа увеличиваем его счётчик.
    #
    # Счётчики складываем в строку-ключ, например "a1b2c1".
    # Строки одинаковой длины и с одинаковым набором букв
    # дадут одинаковый ключ, разные — разные ключи.
    groups = {}  # ключ-счётчики -> [исходные строки]
    for s in strs:
        counts = [0] * 26
        for ch in s:
            counts[ord(ch) - ord('a')] += 1
        key = tuple(counts)  # tuple из 26 чисел — хешируемый ключ
        if key not in groups:
            groups[key] = []
        groups[key].append(s)
    return list(groups.values())

# Сложность: O(n * k) по времени (одна строка — один проход),
# O(26) = O(1) на ключ.
