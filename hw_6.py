# 1. Наибольшая непрерывная возрастающая последовательность
def longest_increasing_run(nums):
    # Идём по массиву один раз. Держим две величины:
    #   cur — длина текущей возрастающей последовательности,
    #   best — максимальная встреченная длина.
    # Если nums[i] > nums[i-1], последовательность продолжается (cur += 1),
    # иначе она оборвалась — начинаем новую с длины 1.
    # После каждого шага обновляем best = max(best, cur).
    # Всего n шагов по O(1) -> O(n) времени.
    if not nums:
        return 0
    cur = best = 1
    for i in range(1, len(nums)):
        if nums[i] > nums[i - 1]:
            cur += 1
        else:
            cur = 1
        if cur > best:
            best = cur
    return best


# 2. Треугольник Паскаля
def pascal_triangle(n):
    # Каждая строка строится из предыдущей:
    #   row[0] = row[-1] = 1 (края всегда единицы),
    #   row[j] = prev[j-1] + prev[j] — сумма двух элементов над ним.
    # Именно это свойство и определяет треугольник Паскаля
    # (каждое число — сумма двух стоящих выше).
    #
    # Сложность: строк в треугольнике n, в i-й строке i элементов,
    # всего ~n^2/2 операций -> O(n^2) времени.
    result = []
    prev = []
    for i in range(n):
        row = [1] * (i + 1)
        for j in range(1, i):
            row[j] = prev[j - 1] + prev[j]
        result.append(row)
        prev = row
    return result


# 3. Размен монет
def coin_change(coins, amount):
    # dp[s] — минимальное число монет для суммы s.
    # База: dp[0] = 0 (нулевая сумма — ноль монет).
    # Переход: чтобы получить сумму s, последней монетой могла быть
    # любая c из coins; тогда до неё нужно было набрать s - c.
    #   dp[s] = min(dp[s - c] + 1) по всем c <= s
    # Корректность: любая оптимальная раздача суммы s имеет
    # последнюю монету c, а остаток s - c раздаётся оптимально — значит
    # перебор всех c даёт оптимум.
    # Невозможные суммы остаются "бесконечностью".
    #
    # Сложность: amount * len(coins) переходов -> O(amount * k) времени.
    INF = float('inf')
    dp = [INF] * (amount + 1)
    dp[0] = 0
    for s in range(1, amount + 1):
        for c in coins:
            if c <= s and dp[s - c] + 1 < dp[s]:
                dp[s] = dp[s - c] + 1
    return dp[amount] if dp[amount] != INF else -1


# 4. Максимальный палиндром в строке
def longest_palindrome(s):
    # Расширение от центра: палиндром определяется своим центром.
    # Центр — либо один символ (палиндром нечётной длины),
    # либо пара соседних символов (чётной). Таких центров 2n-1.
    # Для каждого центра расширяемся в обе стороны, пока символы равны.
    #
    # Сложность: центров O(n), на каждый до O(n) расширений ->
    # O(n^2) времени. Возвращаем саму подстроку.
    if not s:
        return ""

    def expand(left, right):
        while left >= 0 and right < len(s) and s[left] == s[right]:
            left -= 1
            right += 1
        # цикл остановился на первом несовпадении -> границы вернуть на 1
        return left + 1, right - 1

    best_l = best_r = 0
    for i in range(len(s)):
        l1, r1 = expand(i, i)          # нечётный центр
        l2, r2 = expand(i, i + 1)      # чётный центр
        if r1 - l1 > best_r - best_l:
            best_l, best_r = l1, r1
        if r2 - l2 > best_r - best_l:
            best_l, best_r = l2, r2
    return s[best_l:best_r + 1]
